"""Descriptive statistics for the cleaned dataset (JSON + Markdown)."""

from __future__ import annotations

import collections
import json
import statistics
from pathlib import Path
from typing import Any, Iterable

from .pipeline import read_jsonl


def _dist(values: Iterable[float]) -> dict[str, float]:
    xs = sorted(values)
    if not xs:
        return {}
    q = statistics.quantiles(xs, n=4) if len(xs) > 1 else [xs[0]] * 3
    return {"n": len(xs), "min": xs[0], "q1": q[0], "median": q[1], "q3": q[2], "max": xs[-1],
            "mean": round(statistics.fmean(xs), 2)}


def compute_stats(prs: list[dict[str, Any]], evidence: list[dict[str, Any]],
                  build_info: dict[str, Any] | None = None) -> dict[str, Any]:
    ev = {e["pr_id"]: e for e in evidence}
    by_split = collections.Counter(p["split"] for p in prs)
    stats: dict[str, Any] = {
        "prs": len(prs),
        "repositories": len({p["repository"].lower() for p in prs}),
        "split_prs": dict(by_split),
        "split_repositories": {s: len({p["repository"].lower() for p in prs if p["split"] == s})
                               for s in by_split},
        "repository_overlap_between_splits": len(
            {p["repository"].lower() for p in prs if p["split"] == "development"}
            & {p["repository"].lower() for p in prs if p["split"] == "evaluation"}),
        "pilot_prs_included": sum(p.get("in_pilot", False) for p in prs),
        "agent": dict(collections.Counter(p["agent"] for p in prs).most_common()),
        "agent_by_split": {s: dict(collections.Counter(p["agent"] for p in prs if p["split"] == s))
                           for s in by_split},
        "pr_state": dict(collections.Counter(p["pr_state"] for p in prs).most_common()),
        "has_linked_issue": sum(bool(p["linked_issues"]) for p in prs),
        "has_agent_testing_section": sum(bool(p["agent_reported_testing"]) for p in prs),
        "agent_reported_test_failure": sum(p["agent_reported_test_failure"] for p in prs),
        "touches_test_files": sum(bool(p["changed_test_files"]) for p in prs),
        "repository_stars": _dist(p["repository_stars"] for p in prs),
        "requirement_words": _dist(p["requirement_words"] for p in prs),
        "changed_lines": _dist(p["changed_lines"] for p in prs),
        "additions": _dist(p["additions"] for p in prs),
        "deletions": _dist(p["deletions"] for p in prs),
        "changed_files": _dist(p["n_changed_files"] for p in prs),
        "changed_python_files": _dist(len(p["changed_python_files"]) for p in prs),
        "commits": _dist(p["n_commits"] or 0 for p in prs),
        "created_month": dict(sorted(collections.Counter((p["created_at"] or "")[:7] for p in prs).items())),
        "licenses": dict(collections.Counter(p["repository_license"] or "unknown" for p in prs).most_common()),
        "cleaning_rules_fired": dict(collections.Counter(
            r for p in prs for r in p["cleaning_rules_applied"]).most_common()),
    }
    if ev:
        stats["review_evidence"] = {
            "prs_with_human_review": sum(ev[p["pr_id"]]["n_human_reviews"] > 0 for p in prs),
            "prs_with_human_inline_comments": sum(ev[p["pr_id"]]["n_human_inline_comments"] > 0 for p in prs),
            "human_inline_comments": _dist(ev[p["pr_id"]]["n_human_inline_comments"] for p in prs),
        }
    if build_info:
        stats["build"] = build_info
    return stats


def _row(label: str, d: dict[str, float]) -> str:
    if not d:
        return f"| {label} | – | – | – | – | – |"
    return f"| {label} | {d['min']:g} | {d['q1']:g} | {d['median']:g} | {d['q3']:g} | {d['max']:g} |"


def stats_markdown(s: dict[str, Any]) -> str:
    lines = [
        "# Dataset statistics",
        "",
        "Generated by `agent-code-reviewer dataset stats`. Do not edit by hand.",
        "",
        "## Overview",
        "",
        "| Item | Value |",
        "|---|---|",
        f"| PRs | {s['prs']} |",
        f"| Repositories | {s['repositories']} |",
        f"| Development / evaluation PRs | {s['split_prs'].get('development', 0)} / "
        f"{s['split_prs'].get('evaluation', 0)} |",
        f"| Repository overlap between splits | {s['repository_overlap_between_splits']} |",
        f"| Pilot PRs carried over | {s['pilot_prs_included']} |",
        f"| PR state (merged / closed / open) | {s['pr_state'].get('merged', 0)} / "
        f"{s['pr_state'].get('closed', 0)} / {s['pr_state'].get('open', 0)} |",
        f"| With linked issue | {s['has_linked_issue']} |",
        f"| Touch test files | {s['touches_test_files']} |",
        f"| Agent wrote a testing section | {s['has_agent_testing_section']} |",
        f"| Agent reported a failing check | {s['agent_reported_test_failure']} |",
    ]
    if "review_evidence" in s:
        rv = s["review_evidence"]
        lines += [f"| With a human review | {rv['prs_with_human_review']} |",
                  f"| With human inline review comments | {rv['prs_with_human_inline_comments']} |"]
    lines += ["", "## Agents", "", "| Agent | All | Development | Evaluation |", "|---|---|---|---|"]
    for agent, n in s["agent"].items():
        lines.append(f"| {agent} | {n} | {s['agent_by_split'].get('development', {}).get(agent, 0)} | "
                     f"{s['agent_by_split'].get('evaluation', {}).get(agent, 0)} |")
    lines += ["", "## Size distributions", "", "| Measure | Min | Q1 | Median | Q3 | Max |",
              "|---|---|---|---|---|---|",
              _row("Repository stars", s["repository_stars"]),
              _row("Requirement words", s["requirement_words"]),
              _row("Changed lines (+/-)", s["changed_lines"]),
              _row("Changed files", s["changed_files"]),
              _row("Changed Python files", s["changed_python_files"]),
              _row("Commits", s["commits"])]
    if "review_evidence" in s:
        lines.append(_row("Human inline comments", s["review_evidence"]["human_inline_comments"]))
    b = s.get("build")
    if b:
        f, sc = b["metadata_funnel"], b["patch_screening"]
        lines += ["", "## Selection funnel", "", "| Step | PRs |", "|---|---|",
                  f"| AIDev-pop PRs | {f.get('input_prs', 0)} |",
                  f"| Excluded: not Python or ≤{b['parameters']['min_stars_exclusive']} stars | "
                  f"{f.get('excluded_language_or_stars', 0)} |",
                  f"| Excluded: documentation title | {f.get('excluded_documentation_title', 0)} |",
                  f"| Excluded: <{b['parameters']['min_requirement_words']} words of requirement text "
                  f"after cleaning | {f.get('excluded_insufficient_requirement_text', 0)} |",
                  f"| Excluded: duplicate or malformed | {f.get('excluded_duplicate', 0) + f.get('excluded_missing_repository', 0) + f.get('excluded_missing_repository_name_or_pr_number', 0)} |",
                  f"| Eligible PRs (repositories) | {f.get('eligible_prs', 0)} ({f.get('eligible_repositories', 0)}) |",
                  f"| Screened against GitHub (one PR per repository) | {sc.get('screened', 0)} |",
                  f"| Excluded: PR or diff unavailable | {sc.get('excluded_pr_unavailable', 0) + sc.get('excluded_diff_unavailable', 0)} |",
                  f"| Excluded: no Python changes | {sc.get('excluded_no_python_changes', 0)} |",
                  f"| Excluded: >{b['parameters']['max_changed_lines']} changed lines or "
                  f">{b['parameters']['max_changed_files']} files | {sc.get('excluded_too_large', 0)} |",
                  f"| **Final dataset** | **{sc.get('selected', 0)}** |"]
    lines += ["", "## Cleaning rules that fired", "", "| Rule | PRs |", "|---|---|"]
    lines += [f"| {k} | {v} |" for k, v in s["cleaning_rules_fired"].items()]
    return "\n".join(lines) + "\n"


def write_stats(data_dir: Path) -> dict[str, Any]:
    data_dir = Path(data_dir)
    prs = read_jsonl(data_dir / "prs.jsonl")
    ev_path = data_dir / "review_evidence.jsonl"
    evidence = read_jsonl(ev_path) if ev_path.is_file() else []
    info_path = data_dir / "build_info.json"
    info = json.loads(info_path.read_text()) if info_path.is_file() else None
    s = compute_stats(prs, evidence, info)
    (data_dir / "stats.json").write_text(json.dumps(s, indent=2) + "\n", encoding="utf-8")
    (data_dir / "STATS.md").write_text(stats_markdown(s), encoding="utf-8")
    return s
